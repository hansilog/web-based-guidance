-- ---------------------------------------------------------------------
-- 7. Live updates and scheduled reminders (Supabase only)
-- ---------------------------------------------------------------------

do $$
declare
  t text;
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    foreach t in array array['profiles', 'appointments', 'appointment_private', 'counselor_blocks',
                             'notifications', 'waitlist', 'concerns', 'settings', 'broadcasts'] loop
      if not exists (select 1 from pg_publication_tables
                     where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = t) then
        execute format('alter publication supabase_realtime add table public.%I', t);
      end if;
    end loop;
  end if;
end $$;

-- Needs the pg_cron extension: Dashboard -> Database -> Extensions -> pg_cron, then re-run this block.
do $$
begin
  if exists (select 1 from pg_extension where extname = 'pg_cron') then
    perform cron.schedule('granby-reminders', '*/5 * * * *', 'select public.send_due_reminders()');
  end if;
end $$;
