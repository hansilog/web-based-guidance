-- New sign-ups always become students; staff roles are set by an admin
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  meta jsonb := coalesce(new.raw_user_meta_data, '{}'::jsonb);
  uname text := coalesce(nullif(trim(meta ->> 'username'), ''), split_part(new.email, '@', 1));
begin
  insert into public.profiles (auth_id, username, name, email, role, year_level, course, section, consent_at)
  values (
    new.id,
    uname,
    coalesce(nullif(trim(meta ->> 'name'), ''), uname),
    lower(new.email),
    'student',
    meta ->> 'yearLevel',
    meta ->> 'course',
    meta ->> 'section',
    case when meta ? 'consentAt' then now() end
  );
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- Only admins may change roles, activation, login names or emails
create or replace function public.protect_profile() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is not null and not public.is_admin() then
    if new.role is distinct from old.role
       or new.active is distinct from old.active
       or new.auth_id is distinct from old.auth_id
       or lower(new.username) is distinct from lower(old.username)
       or lower(new.email) is distinct from lower(old.email) then
      raise exception 'Only an administrator can change this field' using errcode = '42501';
    end if;
  end if;
  return new;
end $$;

drop trigger if exists protect_profile on public.profiles;
create trigger protect_profile before update on public.profiles
  for each row execute function public.protect_profile();

