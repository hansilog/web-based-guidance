-- A counselor removing a day off frees every slot of that day
create or replace function public.release_day() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  t text;
begin
  for t in select public.office_slots() loop
    perform public.notify_waitlist(old.date, t, old.counselor_id);
  end loop;
  return old;
end $$;

drop trigger if exists release_day on public.counselor_blocks;
create trigger release_day after delete on public.counselor_blocks
  for each row execute function public.release_day();

-- Anonymous reports: force safe defaults, throttle floods, alert counselors
