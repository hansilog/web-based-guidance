-- Login accepts a username: look up the email to sign in with
create or replace function public.email_for_login(p_identifier text) returns text
language sql stable security definer set search_path = public as $$
  select case
    when position('@' in p_identifier) > 0 then lower(trim(p_identifier))
    else (select email from public.profiles where lower(username) = lower(trim(p_identifier)) and active)
  end
$$;

create or replace function public.username_available(p_username text) returns boolean
language sql stable security definer set search_path = public as $$
  select not exists (select 1 from public.profiles where lower(username) = lower(trim(p_username)))
$$;

-- Taken slots for everyone, without saying who booked them
create or replace function public.get_active_bookings()
returns table (id bigint, counselor_id bigint, date date, "time" text, status text)
language sql stable security definer set search_path = public as $$
  select a.id, a.counselor_id, a.date, a.time, a.status
  from public.appointments a
  where a.status in ('pending', 'approved') and not a.walk_in and a.counselor_id is not null
    and auth.uid() is not null
$$;

-- What a reporter may see about their own anonymous concern
create or replace function public.concern_status(p_ref text)
returns table (ref text, status text, response text, created_at timestamptz)
language sql stable security definer set search_path = public as $$
  select c.ref, c.status, c.response, c.created_at
  from public.concerns c where c.ref = upper(trim(p_ref))
$$;

-- Day-before and hour-before reminders (scheduled below with pg_cron)
create or replace function public.send_due_reminders() returns int
language plpgsql security definer set search_path = public as $$
declare
  n_hour int;
  n_day int;
begin
  -- Hour before: student and counselor; also counts as the day-before reminder
  with due as (
    update public.appointments a
    set reminders = a.reminders || '{"day": true, "hour": true}'::jsonb
    where a.status = 'approved' and not a.walk_in
      and not coalesce((a.reminders ->> 'hour')::boolean, false)
      and public.slot_start(a.date, a.time) > now()
      and public.slot_start(a.date, a.time) <= now() + interval '1 hour'
    returning a.*
  ), notes as (
    insert into public.notifications (user_id, message)
    select student_id, 'Starting soon: your ' || type || ' session with '
           || coalesce(nullif(counselor_name, 'Unassigned'), 'your counselor')
           || ' is at ' || to_char(time::time, 'FMHH12:MI AM') || ' today.'
    from due
    union all
    select counselor_id, 'Coming up at ' || to_char(time::time, 'FMHH12:MI AM') || ': '
           || type || ' session with ' || student_name || '.'
    from due where counselor_id is not null
    returning 1
  )
  select count(*) into n_hour from due;

  with due as (
    update public.appointments a
    set reminders = a.reminders || '{"day": true}'::jsonb
    where a.status = 'approved' and not a.walk_in
      and not coalesce((a.reminders ->> 'day')::boolean, false)
      and public.slot_start(a.date, a.time) > now() + interval '1 hour'
      and public.slot_start(a.date, a.time) <= now() + interval '24 hours'
    returning a.*
  ), notes as (
    insert into public.notifications (user_id, message)
    select student_id, 'Reminder: your ' || type || ' session with '
           || coalesce(nullif(counselor_name, 'Unassigned'), 'your counselor')
           || ' is on ' || to_char(date, 'FMDay, Mon FMDD') || ' at '
           || to_char(time::time, 'FMHH12:MI AM')
           || '. If you can''t make it, please reschedule or cancel from your Dashboard.'
    from due
    returning 1
  )
  select count(*) into n_day from due;

  return n_hour + n_day;
end $$;

