-- Students: new bookings are always pending, for themselves, at a valid time
create or replace function public.guard_appointment_insert() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  me public.profiles;
  problem text;
begin
  if auth.uid() is null or public.is_staff() then return new; end if;
  select * into me from public.profiles where auth_id = auth.uid() and active;
  if me.id is null or new.student_id <> me.id then
    raise exception 'You can only book for yourself' using errcode = '42501';
  end if;
  problem := public.slot_problem(new.counselor_id, new.date, new.time);
  if problem <> '' then raise exception '%', problem using errcode = 'P0001'; end if;
  new.student_name := me.name;
  new.student_email := me.email;
  new.counselor_name := coalesce((select name from public.profiles where id = new.counselor_id), 'Unassigned');
  new.status := 'pending';
  new.walk_in := false;
  new.counselor_notes := '';
  new.follow_up := false;
  new.follow_up_reminded_at := null;
  new.checked_on_at := null;
  new.feedback := null;
  new.decided_at := null;
  new.reminders := '{}'::jsonb;
  new.created_at := now();
  return new;
end $$;

drop trigger if exists guard_appointment_insert on public.appointments;
create trigger guard_appointment_insert before insert on public.appointments
  for each row execute function public.guard_appointment_insert();

-- Students may only cancel, reschedule (back to pending) or rate a completed session
create or replace function public.guard_appointment_update() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  problem text;
  rescheduling boolean;
begin
  if auth.uid() is null or public.is_staff() then return new; end if;

  if new.student_id <> old.student_id or new.walk_in <> old.walk_in
     or new.urgent <> old.urgent or new.follow_up <> old.follow_up
     or new.decided_at is distinct from old.decided_at
     or new.check_in is distinct from old.check_in
     or new.created_at <> old.created_at
     or new.follow_up_reminded_at is distinct from old.follow_up_reminded_at
     or new.checked_on_at is distinct from old.checked_on_at then
    raise exception 'Students cannot change this field' using errcode = '42501';
  end if;

  rescheduling := new.date <> old.date or new.time <> old.time
                  or new.counselor_id is distinct from old.counselor_id;

  if new.status <> old.status then
    if old.status not in ('pending', 'approved') or new.status not in ('cancelled', 'pending') then
      raise exception 'Students cannot make that status change' using errcode = '42501';
    end if;
    if new.status = 'pending' and not rescheduling then
      raise exception 'Students cannot make that status change' using errcode = '42501';
    end if;
  end if;

  if rescheduling then
    if new.status <> 'pending' then
      raise exception 'A rescheduled session goes back to pending' using errcode = '42501';
    end if;
    problem := public.slot_problem(new.counselor_id, new.date, new.time);
    if problem <> '' then raise exception '%', problem using errcode = 'P0001'; end if;
    new.counselor_name := coalesce((select name from public.profiles where id = new.counselor_id), 'Unassigned');
  elsif new.counselor_name <> old.counselor_name then
    raise exception 'Students cannot change this field' using errcode = '42501';
  end if;

  if new.counselor_notes <> old.counselor_notes and new.counselor_notes <> '' then
    raise exception 'Students cannot write counselor notes' using errcode = '42501';
  end if;

  if new.feedback is distinct from old.feedback then
    if old.status <> 'completed' or old.feedback is not null then
      raise exception 'Only completed sessions can be rated, once' using errcode = '42501';
    end if;
  end if;
  return new;
end $$;

drop trigger if exists guard_appointment_update on public.appointments;
create trigger guard_appointment_update before update on public.appointments
  for each row execute function public.guard_appointment_update();

-- Tell everyone waiting for a freed slot. Mirrors notifyWaitlist() in store.js.
create or replace function public.notify_waitlist(p_date date, p_time text, p_counselor bigint)
returns int language plpgsql security definer set search_path = public as $$
declare
  n int;
begin
  if public.slot_start(p_date, p_time) <= now() then return 0; end if;
  if exists (select 1 from public.counselor_blocks where counselor_id = p_counselor and date = p_date)
     or exists (select 1 from public.appointments
                where counselor_id = p_counselor and date = p_date and time = p_time
                  and status in ('pending', 'approved') and not walk_in) then
    return 0;
  end if;

  insert into public.notifications (user_id, message)
  select w.student_id,
         'A spot opened up on ' || to_char(p_date, 'Dy, Mon FMDD') || ' at '
         || to_char(p_time::time, 'FMHH12:MI AM')
         || '. Book it from your Dashboard before someone else does.'
  from public.waitlist w
  where w.date = p_date and w.time = p_time
    and (w.counselor_id is null or w.counselor_id = p_counselor);
  get diagnostics n = row_count;

  update public.waitlist set notified_at = now()
  where date = p_date and time = p_time
    and (counselor_id is null or counselor_id = p_counselor);
  return n;
end $$;

create or replace function public.release_slot() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if old.status in ('pending', 'approved') and old.counselor_id is not null and not old.walk_in
     and (new.status not in ('pending', 'approved') or new.date <> old.date
          or new.time <> old.time or new.counselor_id is distinct from old.counselor_id) then
    perform public.notify_waitlist(old.date, old.time, old.counselor_id);
  end if;
  -- A booking that day ends the student's waitlist entries for it
  if new.status in ('pending', 'approved') then
    delete from public.waitlist where student_id = new.student_id and date = new.date;
  end if;
  return new;
end $$;

