-- Start of a session as a real timestamp in the office time zone
create or replace function public.slot_start(p_date date, p_time text) returns timestamptz
language sql stable set search_path = public as $$
  select (p_date + p_time::time) at time zone (select timezone from public.settings where id = 1)
$$;

-- Booking times for a day under the current office hours
create or replace function public.office_slots() returns setof text
language sql stable set search_path = public as $$
  select lpad(h::text, 2, '0') || ':00'
  from public.settings s, generate_series(s.open_hour, s.close_hour - 1) as h
  where s.id = 1 and h is distinct from s.lunch_hour
$$;

-- Why a student can't book this slot ('' when it's fine). Mirrors checkDate() in store.js.
create or replace function public.slot_problem(p_counselor bigint, p_date date, p_time text)
returns text language plpgsql stable security definer set search_path = public as $$
declare
  tz text := (select timezone from public.settings where id = 1);
  today date := (now() at time zone tz)::date;
begin
  if p_date < today then return 'That date has already passed.'; end if;
  if extract(isodow from p_date) > 5 then return 'The guidance office is closed on weekends.'; end if;
  if p_date > today + 60 then return 'You can book up to 60 days ahead.'; end if;
  if exists (select 1 from public.settings s, jsonb_array_elements(s.holidays) h
             where s.id = 1 and h ->> 'date' = p_date::text) then
    return 'The guidance office is closed on this day.';
  end if;
  if p_time not in (select public.office_slots()) then return 'That time is outside office hours.'; end if;
  if public.slot_start(p_date, p_time) <= now() then return 'That time has already passed.'; end if;
  if p_counselor is not null then
    if not exists (select 1 from public.profiles where id = p_counselor and role = 'guidance' and active) then
      return 'That counselor is not available.';
    end if;
    if exists (select 1 from public.counselor_blocks where counselor_id = p_counselor and date = p_date) then
      return 'This counselor is not available on this day.';
    end if;
  end if;
  return '';
end $$;

