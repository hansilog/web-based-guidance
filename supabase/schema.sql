-- Same id scheme as the app: milliseconds * 1000 + random 0..999
create or replace function public.new_id() returns bigint
language sql volatile as $$
  select (floor(extract(epoch from clock_timestamp()) * 1000) * 1000
          + floor(random() * 1000))::bigint
$$;

